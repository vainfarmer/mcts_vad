"""Evaluate complete paired tails with paired video bootstrap; no index substitution.

Use --paired-dir for results generated by --mcts_paired_eval.
Or --ref/--new for separate runs (upstream/API noise is not eliminated).
"""
import argparse
import copy
import json
from pathlib import Path
import sys
import numpy as np
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from evaluate import load_ground_truth,compute_temporal_map,compute_frame_auc,compute_video_level


# 先校验manifest、视频集合和每条结果的指纹，避免只评估成功子集而虚增指标。
def load_results(directory):
    records={}
    for path in sorted(Path(directory).glob('*.json')):
        r=json.loads(path.read_text(encoding='utf-8'))
        if 'video_path' not in r or 'anomalies' not in r: continue
        vid=Path(r['video_path']).stem
        if vid in records: raise ValueError('Duplicate video: '+vid)
        records[vid]=r
    manifest_path=Path(directory)/'metadata/manifest.json'
    if not manifest_path.exists(): raise ValueError('Batch manifest required: '+str(manifest_path))
    manifest=json.loads(manifest_path.read_text(encoding='utf-8'))
    expected={Path(v).stem for v in manifest['videos']}
    if set(records)!=expected:
        raise ValueError(f'Incomplete/extra results: missing={expected-set(records)}, extra={set(records)-expected}')
    if any(r.get('experiment_fingerprint')!=manifest['fingerprint'] for r in records.values()):
        raise ValueError('Result fingerprint mismatch')
    return records,manifest


# 配对按视频重采样，而不是按预测段采样；重复抽到的视频必须分配独立ID。
def bootstrap(gt,off,on,fps,repeats,seed):
    rng=np.random.default_rng(seed); ids=sorted(gt); deltas=[]
    for _ in range(repeats):
        sampled=rng.choice(ids,len(ids),replace=True)
        # Repeated draws get independent video IDs; never overwrite dictionary keys.
        g={str(i):gt[v] for i,v in enumerate(sampled)}
        a={str(i):off[v] for i,v in enumerate(sampled)}; b={str(i):on[v] for i,v in enumerate(sampled)}
        deltas.append(compute_temporal_map(g,b,fps)['mAP']-compute_temporal_map(g,a,fps)['mAP'])
    return {'repeats':repeats,'seed':seed,'delta_ci95':np.percentile(deltas,[2.5,97.5]).tolist(),
            'fraction_delta_positive':float(np.mean(np.asarray(deltas)>0))}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--paired-dir'); p.add_argument('--ref'); p.add_argument('--new')
    p.add_argument('--label-path',required=True); p.add_argument('--fps',type=int,default=30)
    p.add_argument('--output',required=True); p.add_argument('--bootstrap',type=int,default=1000)
    p.add_argument('--seed',type=int,default=42)
    a=p.parse_args()
    if a.bootstrap<=0 or a.fps<=0: p.error('fps and bootstrap must be positive')
    if bool(a.paired_dir)==bool(a.ref or a.new): p.error('Use paired-dir OR ref and new')
    if a.paired_dir:
        on,manifest=load_results(a.paired_dir)
        if not manifest['config']['mcts']['paired_eval']: raise ValueError('Manifest is not paired')
        off={k:v['paired_results']['original_off'] for k,v in on.items()}
        skip={k:v['paired_results']['skip_only'] for k,v in on.items()}
        arms={'off':off,'on':on,'skip_only':skip}
    else:
        if not a.ref or not a.new: p.error('Both ref and new required')
        off,moff=load_results(a.ref); on,manifest=load_results(a.new)
        left=copy.deepcopy(moff); right=copy.deepcopy(manifest)
        for m in (left,right): m.pop('fingerprint',None); m['config'].pop('mcts',None)
        if left!=right: raise ValueError('Non-MCTS experiment settings differ')
        arms={'off':off,'on':on}
    if set(off)!=set(on): raise ValueError('Video lists differ')
    labels=load_ground_truth(a.label_path)
    if not set(on)<=set(labels): raise ValueError('Missing ground-truth labels')
    gt={v:labels[v] for v in on}
    report={'paired':bool(a.paired_dir),'video_count':len(gt),'label_video_count':len(labels),
            'subset_evaluation':len(gt)!=len(labels),'manifest_fingerprint':manifest['fingerprint'], 'arms':{}}
    for name,pred in arms.items():
        report['arms'][name]={'temporal':compute_temporal_map(gt,pred,a.fps),
            'frame':compute_frame_auc(gt,pred,a.fps),'video':compute_video_level(gt,pred),
            'predictions':sum(len(x['anomalies']) for x in pred.values()),
            'per_category':{c:compute_temporal_map({k:v for k,v in gt.items() if v['category']==c},pred,a.fps)
                            for c in sorted({v['category'] for v in gt.values()})}}
    report['bootstrap_on_minus_off']=bootstrap(gt,off,on,a.fps,a.bootstrap,a.seed)
    if 'skip_only' in arms: report['bootstrap_on_minus_skip']=bootstrap(gt,arms['skip_only'],on,a.fps,a.bootstrap,a.seed)
    traces=[r.get('mcts_trace') or {} for r in on.values()]
    candidates=[v for t in traces for v in t.get('candidates',{}).values()]
    from collections import Counter
    report['refinement']={'candidate_count':len(candidates),'applied':sum(bool(c.get('applied')) for c in candidates),
        'logical_requests':sum(t.get('logical_requests',0) for t in traces),
        'images_sent':sum(t.get('images_sent',0) for t in traces),
        'reasons':dict(Counter(c.get('reason','unknown') for c in candidates)),
        'elapsed_seconds':sum(c.get('elapsed_seconds',0) for c in candidates)}
    Path(a.output).parent.mkdir(parents=True,exist_ok=True)
    Path(a.output).write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')


if __name__=='__main__': main()
